import { supabase } from './supabase'
import type { Game, Category } from './types'

export type CardGame = Game & { categories?: { name: string; slug?: string } }
export type FullGame = Game & { categories?: { name: string; slug: string } }

export const CARD_SELECT = 'id, title, slug, thumbnail, short_description, is_new, is_hot, is_featured, views, category_id, categories(name)'
const CARD_SELECT_INNER = 'id, title, slug, thumbnail, short_description, is_new, is_hot, is_featured, views, category_id, categories!inner(name, slug)'

export const HOME_CATEGORIES = [
  { slug: 'puzzle-games', label: 'Puzzle Games' },
  { slug: 'racing-games', label: 'Racing Games' },
  { slug: 'sports-games', label: 'Sports Games' },
  { slug: 'action-games', label: 'Action Games' },
  { slug: 'arcade-games', label: 'Arcade Games' },
  { slug: 'strategy-games', label: 'Strategy Games' },
]

export interface HomeData {
  featured: CardGame[]
  popular: CardGame[]
  newGames: CardGame[]
  byCategory: Record<string, CardGame[]>
}

export async function fetchHomeData(): Promise<HomeData> {
  const [featRes, popRes, newRes, ...catRes] = await Promise.all([
    supabase.from('games').select(CARD_SELECT).eq('is_active', true).eq('is_featured', true).order('views', { ascending: false }).limit(10),
    supabase.from('games').select(CARD_SELECT).eq('is_active', true).order('views', { ascending: false }).limit(12),
    supabase.from('games').select(CARD_SELECT).eq('is_active', true).eq('is_new', true).order('created_at', { ascending: false }).limit(10),
    ...HOME_CATEGORIES.map(cat =>
      supabase.from('games').select(CARD_SELECT_INNER).eq('is_active', true).eq('categories.slug', cat.slug).order('views', { ascending: false }).limit(10)
    ),
  ])
  const byCategory: Record<string, CardGame[]> = {}
  HOME_CATEGORIES.forEach((cat, i) => { byCategory[cat.slug] = (catRes[i].data ?? []) as CardGame[] })
  return {
    featured: (featRes.data ?? []) as CardGame[],
    popular: (popRes.data ?? []) as CardGame[],
    newGames: (newRes.data ?? []) as CardGame[],
    byCategory,
  }
}

export async function fetchCollectionGames(categorySlugs?: string[]): Promise<CardGame[]> {
  let q = supabase.from('games').select(CARD_SELECT_INNER).eq('is_active', true).order('views', { ascending: false })
  if (categorySlugs?.length) q = q.in('categories.slug', categorySlugs)
  const { data } = await q.limit(48)
  return (data ?? []) as CardGame[]
}

export async function fetchPopularGames(): Promise<CardGame[]> {
  const { data } = await supabase.from('games').select(CARD_SELECT).eq('is_active', true).order('views', { ascending: false }).limit(60)
  return (data ?? []) as CardGame[]
}

export interface CategoryData { category: Category | null; games: CardGame[]; total: number }

export async function fetchCategoryData(slug: string, page: number, pageSize: number): Promise<CategoryData> {
  const [catRes, gamesRes] = await Promise.all([
    supabase.from('categories').select('*').eq('slug', slug).maybeSingle(),
    supabase.from('games').select(CARD_SELECT_INNER).eq('is_active', true).eq('categories.slug', slug)
      .order('views', { ascending: false }).range(page * pageSize, (page + 1) * pageSize - 1),
  ])
  const category = catRes.data as Category | null
  const { count } = await supabase.from('games').select('*', { count: 'exact', head: true })
    .eq('is_active', true).eq('category_id', category?.id ?? 0)
  return { category, games: (gamesRes.data ?? []) as CardGame[], total: count ?? 0 }
}

let instructionsPromise: Promise<Record<string, string>> | null = null

/** Publisher "how to play" text keyed by source_id (generated by scripts/build-game-instructions.mjs). */
export function fetchGameInstructions(): Promise<Record<string, string>> {
  instructionsPromise ??= fetch('/data/game-instructions.json')
    .then(r => (r.ok ? r.json() : {}))
    .catch(() => ({}))
  return instructionsPromise
}

export async function fetchNewGames(): Promise<CardGame[]> {
  const { data } = await supabase.from('games').select(CARD_SELECT).eq('is_active', true).eq('is_new', true)
    .order('created_at', { ascending: false }).limit(60)
  return (data ?? []) as CardGame[]
}
